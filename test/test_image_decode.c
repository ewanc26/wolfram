/* The RGBA at one pixel, as a comparison helper: the decode is RGBA8
 * tightly packed, so a pixel is four bytes in order. */
static int pixel_is(const wf_image_rgba *img, int x, int y, unsigned char r,
                    unsigned char g, unsigned char b, unsigned char a) {
    const unsigned char *p =
        img->pixels + ((size_t)y * (size_t)img->width + (size_t)x) * 4u;
    return p[0] == r && p[1] == g && p[2] == b && p[3] == a;
}

