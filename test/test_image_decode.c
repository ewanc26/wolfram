/* PNG header claiming 4096x4096 over a stub body. */
static const unsigned char kBigHeader[] = {
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00,
    0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
    0x10, 0x00, 0x08, 0x06, 0x00, 0x00, 0x00, 0xf2, 0xa3, 0x24, 0x17,
    0x00, 0x00, 0x00, 0x09, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0x63,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0xb1, 0x0d, 0xb6, 0x93, 0x00,
    0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};

int main(void) {
    /* Exact fit: nothing to scale, every pixel is the source colour. */
    wf_image_rgba img = {0};
    wf_status s = wf_image_decode_rgba(kGreen4, sizeof(kGreen4), 0, &img);
    WF_CHECK(s == WF_OK);
    WF_CHECK(img.width == 4 && img.height == 4);
    WF_CHECK(pixel_is(&img, 0, 0, 0, 255, 0, 255));
    WF_CHECK(pixel_is(&img, 3, 3, 0, 255, 0, 255));
    wf_image_rgba_free(&img);
    WF_CHECK(img.pixels == NULL && img.width == 0 && img.height == 0);

    /* Asking for more than the image has must not upscale. */
    s = wf_image_decode_rgba(kGreen4, sizeof(kGreen4), 64, &img);
    WF_CHECK(s == WF_OK && img.width == 4 && img.height == 4);
    wf_image_rgba_free(&img);

    /* Square downscale keeps the aspect ratio: 64x64 asked down to 32. */
    s = wf_image_decode_rgba(kHalf64, sizeof(kHalf64), 32, &img);
    WF_CHECK(s == WF_OK);
    WF_CHECK(img.width == 32 && img.height == 32);
    /* The box filter averages whole 2x2 blocks of one colour each, so the
     * result is exact rather than approximate: that is what makes the
     * downscale path assertable at all. */
    WF_CHECK(pixel_is(&img, 0, 0, 255, 0, 0, 255));
    WF_CHECK(pixel_is(&img, 15, 31, 255, 0, 0, 255));
    WF_CHECK(pixel_is(&img, 16, 0, 0, 0, 255, 255));
    WF_CHECK(pixel_is(&img, 31, 31, 0, 0, 255, 255));
    wf_image_rgba_free(&img);

    /* Non-square: the longest side is capped and the short one follows. */
    s = wf_image_decode_rgba(kWide64, sizeof(kWide64), 32, &img);
    WF_CHECK(s == WF_OK);
    WF_CHECK(img.width == 32 && img.height == 16);
    WF_CHECK(pixel_is(&img, 0, 0, 255, 0, 0, 255));
    WF_CHECK(pixel_is(&img, 31, 15, 0, 0, 255, 255));
    wf_image_rgba_free(&img);

    /* Premultiplied averaging: a transparent black beside an opaque red
     * has to average to red at half alpha. Averaging the colour channels
     * on their own would give half-brightness red and a dark fringe. */
    s = wf_image_decode_rgba(kAlpha2, sizeof(kAlpha2), 1, &img);
    WF_CHECK(s == WF_OK);
    WF_CHECK(img.width == 1 && img.height == 1);
    WF_CHECK(pixel_is(&img, 0, 0, 255, 0, 0, 127));
    wf_image_rgba_free(&img);

    /* Refused before anything is allocated: the size cap is what keeps a
     * hostile header from turning into a full-size decode. */
    s = wf_image_decode_rgba(kBigHeader, sizeof(kBigHeader), 0, &img);
    WF_CHECK(s == WF_ERR_UNSUPPORTED);
    WF_CHECK(img.pixels == NULL && img.width == 0 && img.height == 0);

    /* Arguments. */
    WF_CHECK(wf_image_decode_rgba(NULL, 10, 0, &img) == WF_ERR_INVALID_ARG);
    WF_CHECK(wf_image_decode_rgba(kGreen4, 0, 0, &img) == WF_ERR_INVALID_ARG);
    WF_CHECK(wf_image_decode_rgba(kGreen4, sizeof(kGreen4), 0, NULL) ==
             WF_ERR_INVALID_ARG);

    /* Bytes that are not an image: the result is left zeroed, so a caller
     * that ignores the status and frees anyway cannot leak or double
     * free. */
    img.pixels = (unsigned char *)&img;
    img.width = 7;
    img.height = 7;
    s = wf_image_decode_rgba("not an image", 11, 0, &img);
    WF_CHECK(s == WF_ERR_PARSE);
    WF_CHECK(img.pixels == NULL && img.width == 0 && img.height == 0);

    /* Freeing a zeroed struct is the "nothing loaded" path. */
    wf_image_rgba_free(&img);
    wf_image_rgba_free(NULL);

    /* The dimension probe and the decoder agree about the same bytes. */
    int w = 0, h = 0;
    WF_CHECK(wf_image_dimensions(kHalf64, sizeof(kHalf64), &w, &h) == WF_OK);
    WF_CHECK(w == 64 && h == 64);
    WF_CHECK(wf_image_dimensions(kBigHeader, sizeof(kBigHeader), &w, &h) ==
             WF_OK);
    WF_CHECK(w == 4096 && h == 4096);

    WF_TEST_SUMMARY();
}
